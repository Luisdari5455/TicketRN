// tools/gen-escpos-logo.js
// Convierte assets/EEMQ2.png a bytes ESC/POS (GS v 0) y genera src/printing/logo.ts
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

// Convierte RGBA → 1-bit (umbral simple)
function rgbaTo1b(bitmap, width, height, threshold = 180) {
  const bytesPerRow = Math.ceil(width / 8);
  const out = Buffer.alloc(bytesPerRow * height);
  for (let y = 0; y < height; y++) {
    for (let xb = 0; xb < bytesPerRow; xb++) {
      let byte = 0;
      for (let b = 0; b < 8; b++) {
        const x = xb * 8 + b;
        let bit = 0;
        if (x < width) {
          const idx = (y * width + x) * 4;
          const r = bitmap[idx], g = bitmap[idx + 1], bl = bitmap[idx + 2], a = bitmap[idx + 3];
          const gray = a === 0 ? 255 : Math.round(0.299 * r + 0.587 * g + 0.114 * bl);
          bit = gray < threshold ? 1 : 0; // 1 = negro
        }
        byte |= (bit << (7 - b));
      }
      out[y * bytesPerRow + xb] = byte;
    }
  }
  return { out, bytesPerRow };
}

(async () => {
  // Uso:
  // node tools/gen-escpos-logo.js [rutaPng] [anchoObjetivo] [limitePapel] [rutaSalidaTS] [umbral]
  // Ej: node tools/gen-escpos-logo.js ./assets/EEMQ2.png 180 384 ./src/printing/logo.ts 180
  const srcPng = path.resolve(process.argv[2] || 'assets/EEMQ2.png');
  const targetW = parseInt(process.argv[3] || '200', 10);   // ⬅️ más chico = logo más pequeño
  const paperW  = parseInt(process.argv[4] || '384', 10);   // 384 (58 mm), 576/640 (80 mm)
  const dstTs   = path.resolve(process.argv[5] || 'src/printing/logo.ts');
  const thresh  = parseInt(process.argv[6] || '180', 10);   // umbral BN (más bajo = más oscuro)

  const img = sharp(srcPng).flatten({ background: { r: 255, g: 255, b: 255 }});
  const meta = await img.metadata();

  // ancho final: no pasarse del objetivo ni del ancho del papel
  const finalW = Math.max(8, Math.min(targetW, paperW, meta.width || targetW));
  const resized = img
    .resize({ width: finalW, fit: 'inside', withoutEnlargement: true })
    .ensureAlpha()
    .raw();

  const { data, info } = await resized.toBuffer({ resolveWithObject: true });
  const { out, bytesPerRow } = rgbaTo1b(data, info.width, info.height, thresh);

  // ESC/POS Raster: GS v 0 m xL xH yL yH + data
  const m = 0; // normal
  const xL = bytesPerRow & 0xff, xH = (bytesPerRow >> 8) & 0xff;
  const yL = info.height & 0xff, yH = (info.height >> 8) & 0xff;
  const header = Buffer.from([0x1D, 0x76, 0x30, m, xL, xH, yL, yH]);
  const payload = Buffer.concat([header, out]);

  const arr = Array.from(payload.values());
  const ts = `// AUTO-GENERATED by tools/gen-escpos-logo.js
export const LOGO_BYTES: number[] = [${arr.join(',')}];
`;
  fs.mkdirSync(path.dirname(dstTs), { recursive: true });
  fs.writeFileSync(dstTs, ts);
  console.log(`OK → ${dstTs} (${info.width}x${info.height}px, bytes/row=${bytesPerRow})`);
})().catch(e => {
  console.error('Logo gen failed:', e);
  process.exit(1);
});
